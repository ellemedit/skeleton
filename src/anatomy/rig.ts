/**
 * Sided bone templates (the left side). The right side is generated by
 * mirroring the X offset. `parentSided` controls whether the parent name also
 * gets an L/R suffix.
 */
interface SidedBoneTemplate {
  readonly base: string;
  readonly parent: string;
  readonly parentSided: boolean;
  readonly offset: readonly [number, number, number];
  readonly shape: BoneShape;
  readonly length?: number;
  readonly radius?: number;
  readonly size?: readonly [number, number, number];
  readonly meshOffset?: readonly [number, number, number];
}

