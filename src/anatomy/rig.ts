/**
 * Data-driven definition of the mannequin: a skeleton of joints (bones) and a
 * set of muscle overlays attached to those bones. Everything is plain data so
 * the figure can be rebuilt, tuned, or inspected without touching render code.
 *
 * Conventions
 * -----------
 * - Units are meters, Y is up, the figure faces +Z, its **left** side is +X.
 * - Each bone is a group whose origin sits at its proximal joint. Limb meshes
 *   extend down the local -Y axis, so the neutral build (all rotations 0) is a
 *   figure standing upright with arms at its sides.
 */

export type BoneShape = "capsule" | "box" | "sphere";

export interface BoneDef {
  readonly name: string;
  readonly parent: string | null;
  /** Offset from the parent joint origin, in the parent's local frame. */
  readonly offset: readonly [number, number, number];
  readonly shape: BoneShape;
  /** Capsule: segment length down -Y. */
  readonly length?: number;
  /** Capsule/sphere radius. */
  readonly radius?: number;
  /** Box half-extents are size/2. */
  readonly size?: readonly [number, number, number];
  /** Optional offset of the mesh within the bone group. */
  readonly meshOffset?: readonly [number, number, number];
}

/** Base id of a muscle group (side-agnostic; used when authoring exercises). */
export type MuscleId =
  | "quadriceps"
  | "hamstrings"
  | "adductors"
  | "gluteus"
  | "calves"
  | "pectoral"
  | "latissimus"
  | "trapezius"
  | "deltoid"
  | "biceps"
  | "triceps"
  | "forearm"
  | "abdominals"
  | "erector_spinae";

export type MuscleRegion = "legs" | "back" | "chest" | "shoulders" | "arms" | "core";

interface MuscleDef {
  readonly id: MuscleId;
  /** Bone (base name) the muscle is attached to. */
  readonly parent: string;
  /** Whether the parent bone itself is sided (gets an L/R suffix). */
  readonly parentSided: boolean;
  /** Whether to create mirrored L/R copies of the muscle. */
  readonly sided: boolean;
  /** Offset within the (left) parent bone's local frame. */
  readonly offset: readonly [number, number, number];
  /** Ellipsoid radii of the muscle bulge. */
  readonly size: readonly [number, number, number];
}

export interface MuscleInstance {
  /** Unique instance name, e.g. "quadriceps_L". */
  readonly name: string;
  /** Side-agnostic group id, e.g. "quadriceps". */
  readonly id: MuscleId;
  /** Exact bone name this instance attaches to, e.g. "hipL". */
  readonly bone: string;
  readonly offset: readonly [number, number, number];
  readonly size: readonly [number, number, number];
}

export interface MuscleInfo {
  readonly label: string;
  readonly region: MuscleRegion;
}

