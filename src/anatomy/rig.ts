function mirrorX(o: readonly [number, number, number]): [number, number, number] {
  return [-o[0], o[1], o[2]];
}

/** Fully expanded list of bones (central + L/R sided), parents before children. */
export const BONES: BoneDef[] = (() => {
  const out: BoneDef[] = [...CENTRAL_BONES];
  for (const side of ["L", "R"] as const) {
    for (const t of SIDED_BONES) {
      const parent = t.parentSided ? `${t.parent}${side}` : t.parent;
      const offset = side === "L" ? t.offset : mirrorX(t.offset);
      out.push({
        name: `${t.base}${side}`,
        parent,
        offset,
        shape: t.shape,
        length: t.length,
        radius: t.radius,
        size: t.size,
        meshOffset: t.meshOffset,
      });
    }
  }
  return out;
})();

