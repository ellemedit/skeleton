/** Expand muscle definitions into concrete per-side instances. */
export const MUSCLES: MuscleInstance[] = (() => {
  const out: MuscleInstance[] = [];
  for (const m of MUSCLE_DEFS) {
    if (m.sided) {
      for (const side of ["L", "R"] as const) {
        const bone = m.parentSided ? `${m.parent}${side}` : m.parent;
        const offset = side === "L" ? [...m.offset] as [number, number, number] : mirrorX(m.offset);
        out.push({ name: `${m.id}_${side}`, id: m.id, bone, offset, size: m.size });
      }
    } else {
      out.push({ name: m.id, id: m.id, bone: m.parent, offset: [...m.offset] as [number, number, number], size: m.size });
    }
  }
  return out;
})();

